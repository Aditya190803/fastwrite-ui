import { test, expect } from '@playwright/test';

test.describe('Results Page', () => {
  test.beforeEach(async ({ page }) => {
    // Set up mock documentation result
    await page.goto('/');
    await page.evaluate(() => {
      localStorage.setItem('documentationResult', JSON.stringify({
        textContent: `# Test Project Documentation

## Overview

This is a test project documentation generated by FastWrite.

## Features

- Feature 1: Lorem ipsum dolor sit amet
- Feature 2: Consectetur adipiscing elit
- Feature 3: Sed do eiusmod tempor

## Installation

\`\`\`bash
npm install test-project
\`\`\`

## Usage

\`\`\`javascript
import { test } from 'test-project';
test.run();
\`\`\`

## API Reference

### \`test.run()\`

Runs the test suite.

| Parameter | Type | Description |
|-----------|------|-------------|
| options | object | Configuration options |

## Conclusion

Thank you for using Test Project!
`,
        visualContent: ''
      }));
      
      localStorage.setItem('documentationGenerationMeta', JSON.stringify({
        provider: 'openai',
        model: 'gpt-4o',
        prompt: 'Generate documentation',
        generatedAt: Date.now()
      }));
    });
    
    await page.goto('/results');
  });

  test('should display documentation content', async ({ page }) => {
    await expect(page.getByText('Test Project Documentation')).toBeVisible();
  });

  test('should have back to generator link', async ({ page }) => {
    const backButton = page.getByRole('link', { name: /back|generator/i });
    await expect(backButton).toBeVisible();
  });

  test('should have export buttons', async ({ page }) => {
    // Check for export options
    const markdownExport = page.getByRole('button', { name: /markdown|\.md/i });
    const pdfExport = page.getByRole('button', { name: /pdf/i });
    
    // At least one export option should exist
    const hasMd = await markdownExport.isVisible().catch(() => false);
    const hasPdf = await pdfExport.isVisible().catch(() => false);
    
    expect(hasMd || hasPdf).toBeTruthy();
  });

  test('should have edit functionality', async ({ page }) => {
    const editButton = page.getByRole('button', { name: /edit/i });
    await expect(editButton).toBeVisible();
    
    // Click edit
    await editButton.click();
    
    // Should show textarea or editable area
    const textarea = page.locator('textarea');
    await expect(textarea).toBeVisible();
    
    // Should have save and cancel buttons
    const saveButton = page.getByRole('button', { name: /save/i });
    const cancelButton = page.getByRole('button', { name: /cancel/i });
    
    await expect(saveButton).toBeVisible();
    await expect(cancelButton).toBeVisible();
  });

  test('should save edited content', async ({ page }) => {
    const editButton = page.getByRole('button', { name: /edit/i });
    await editButton.click();
    
    const textarea = page.locator('textarea');
    await textarea.fill('# Modified Documentation\n\nThis content has been modified.');
    
    const saveButton = page.getByRole('button', { name: /save/i });
    await saveButton.click();
    
    // Should show success message
    await expect(page.locator('[data-sonner-toast]').first()).toBeVisible({ timeout: 5000 });
    
    // Content should be updated
    await expect(page.getByText('Modified Documentation')).toBeVisible();
  });

  test('should cancel edit without saving', async ({ page }) => {
    const editButton = page.getByRole('button', { name: /edit/i });
    await editButton.click();
    
    const textarea = page.locator('textarea');
    await textarea.fill('# Should Not Be Saved');
    
    const cancelButton = page.getByRole('button', { name: /cancel/i });
    await cancelButton.click();
    
    // Original content should still be there
    await expect(page.getByText('Test Project Documentation')).toBeVisible();
    await expect(page.getByText('Should Not Be Saved')).not.toBeVisible();
  });

  test('should render code blocks with syntax highlighting', async ({ page }) => {
    // Look for code blocks
    const codeBlocks = page.locator('pre code, .prism-code, [class*="syntax"]');
    await expect(codeBlocks.first()).toBeVisible();
  });

  test('should have copy button on code blocks', async ({ page }) => {
    // Hover over a code block to reveal copy button
    const codeBlock = page.locator('pre').first();
    await codeBlock.hover();
    
    // Look for copy button
    const copyButton = page.locator('button').filter({ has: page.locator('[class*="copy"], svg') }).first();
    
    // Should have some interactive element for copying
    const buttonCount = await copyButton.count();
    expect(buttonCount).toBeGreaterThanOrEqual(0);
  });

  test('should display table of contents on desktop', async ({ page }) => {
    await page.setViewportSize({ width: 1280, height: 800 });
    
    // TOC should be visible
    const toc = page.locator('[class*="toc"], [class*="TableOfContents"], aside').first();
    const hasToc = await toc.isVisible().catch(() => false);
    
    if (hasToc) {
      // Should contain links to sections
      const tocLinks = toc.locator('a');
      const linkCount = await tocLinks.count();
      expect(linkCount).toBeGreaterThan(0);
    }
  });
});

test.describe('Results Page - History', () => {
  test.beforeEach(async ({ page }) => {
    await page.goto('/');
    
    // Set up mock history
    await page.evaluate(() => {
      const historyEntries = [
        {
          id: '1',
          result: {
            textContent: '# First Doc\n\nFirst documentation',
            visualContent: ''
          },
          sourceName: 'project-1',
          sourceType: 'github',
          generatedAt: Date.now() - 86400000, // 1 day ago
          provider: 'openai',
          model: 'gpt-4o'
        },
        {
          id: '2',
          result: {
            textContent: '# Second Doc\n\nSecond documentation',
            visualContent: ''
          },
          sourceName: 'project-2.zip',
          sourceType: 'zip',
          generatedAt: Date.now() - 3600000, // 1 hour ago
          provider: 'google',
          model: 'gemini-2.0-flash'
        }
      ];
      
      localStorage.setItem('documentationHistory', JSON.stringify(historyEntries));
      localStorage.setItem('documentationResult', JSON.stringify({
        textContent: '# Current Doc',
        visualContent: ''
      }));
    });
    
    await page.goto('/results');
  });

  test('should have history panel', async ({ page }) => {
    const historyButton = page.getByRole('button', { name: /history/i });
    const hasHistoryButton = await historyButton.isVisible().catch(() => false);
    
    if (hasHistoryButton) {
      await historyButton.click();
      
      // History panel should open
      const historyPanel = page.locator('[class*="sheet"], [class*="drawer"], [role="dialog"]').first();
      await expect(historyPanel).toBeVisible();
    }
  });
});

test.describe('Results Page - Export', () => {
  test.beforeEach(async ({ page }) => {
    await page.goto('/');
    await page.evaluate(() => {
      localStorage.setItem('documentationResult', JSON.stringify({
        textContent: '# Export Test\n\nContent to export',
        visualContent: ''
      }));
    });
    await page.goto('/results');
  });

  test('should download markdown file', async ({ page }) => {
    const downloadPromise = page.waitForEvent('download');
    
    const mdButton = page.getByRole('button', { name: /markdown|\.md/i });
    if (await mdButton.isVisible()) {
      await mdButton.click();
      
      const download = await downloadPromise;
      expect(download.suggestedFilename()).toMatch(/\.md$/);
    }
  });
});
