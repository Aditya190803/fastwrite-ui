import { useState } from "react";
import { toast } from "sonner";
import { Download, Loader2, Type } from "lucide-react";
import { Button } from "@/components/ui/button";
import { DocumentationResult } from "@/types/documentation";

interface LatexExportProps {
  result: DocumentationResult;
}

const LatexExport = ({ result }: LatexExportProps) => {
  const [exporting, setExporting] = useState(false);

  const convertToLatex = (markdown: string) => {
    // Very basic markdown to latex conversion
    let latex = markdown
      .replace(/\\/g, "\\\\")
      .replace(/#/g, "\\#")
      .replace(/\$/g, "\\$")
      .replace(/%/g, "\\%")
      .replace(/&/g, "\\&")
      .replace(/_/g, "\\_")
      .replace(/{/g, "\\{")
      .replace(/}/g, "\\}")
      .replace(/~/g, "\\textasciitilde")
      .replace(/\^/g, "\\textasciicircum");

    // Convert headers (approximate)
    latex = latex.replace(/^\\#\\#\\# (.+)$/gm, "\\subsubsection{$1}");
    latex = latex.replace(/^\\#\\# (.+)$/gm, "\\subsection{$1}");
    latex = latex.replace(/^\\# (.+)$/gm, "\\section{$1}");

    // Convert lists
    latex = latex.replace(/^\* (.+)$/gm, "\\item $1");
    // This is very primitive and won't handle nested lists correctly without more work
    // Wrap items in itemize
    // (This is just a starter implementation)

    const fullTemplate = `
\\documentclass{article}
\\usepackage[utf8]{inputenc}
\\usepackage[T1]{fontenc}
\\usepackage{hyperref}

\\title{${result.sourceName || "Project Documentation"}}
\\author{Generated by FastWrite}
\\date{\\today}

\\begin{document}

\\maketitle

${latex}

\\end{document}
    `.trim();

    return fullTemplate;
  };

  const downloadLatex = async () => {
    if (!result) return;

    try {
      setExporting(true);
      const latexContent = convertToLatex(result.textContent);

      const element = document.createElement("a");
      const file = new Blob([latexContent], { type: "application/x-latex" });
      element.href = URL.createObjectURL(file);
      element.download = "documentation.tex";
      document.body.appendChild(element);
      element.click();
      document.body.removeChild(element);

      toast.success("LATEX_PROTOCOL_EXPORT_COMPLETE");
    } catch (error) {
      console.error("Failed to export LaTeX:", error);
      toast.error("LATEX_EXPORT_ERROR");
    } finally {
      setExporting(false);
    }
  };

  return (
    <Button 
      variant="outline"
      onClick={downloadLatex} 
      className="h-12 rounded-none border-white/10 hover:border-primary/40 bg-zinc-950 hover:bg-primary/5 text-[10px] font-mono uppercase tracking-[0.2em] px-6 group relative overflow-hidden industrial-border transition-all duration-300" 
      disabled={exporting}
    >
      <div className="flex items-center gap-3 relative z-10">
        {exporting ? (
          <Loader2 size={12} className="animate-spin text-primary" />
        ) : (
          <Type size={12} className="text-primary group-hover:scale-110 transition-transform" />
        )}
        <span>{exporting ? "CONVERTING..." : "EXP_LATEX"}</span>
      </div>
      <div className="absolute top-0 right-0 w-2 h-2 bg-primary/20" />
      <div className="absolute bottom-0 left-0 w-2 h-2 bg-primary/20" />
    </Button>
  );
};

export default LatexExport;
