function convertMarkdownToHtml(markdown: string): string {
  let html = markdown;

  // Headers
  html = html.replace(/^### (.*$)/gim, '<h3>$1</h3>');
  html = html.replace(/^## (.*$)/gim, '<h2>$1</h2>');
  html = html.replace(/^# (.*$)/gim, '<h1>$1</h1>');

  // Bold
  html = html.replace(/\*\*(.*?)\*\*/gim, '<strong>$1</strong>');

  // Italic
  html = html.replace(/\*(.*?)\*/gim, '<em>$1</em>');

  // Code blocks
  html = html.replace(/```(\w*)\n([\s\S]*?)```/gim, '<pre><code class="language-$1">$2</code></pre>');

  // Inline code
  html = html.replace(/`([^`]+)`/gim, '<code>$1</code>');

  // Blockquotes
  html = html.replace(/^\> (.*$)/gim, '<blockquote>$1</blockquote>');

  // Unordered lists
  html = html.replace(/^\- (.*$)/gim, '<li>$1</li>');
  html = html.replace(/(<li>.*<\/li>)\n(?=<li>)/gim, '$1');
  html = html.replace(/(<li>.*<\/li>)(?!\n<li>)/gims, '<ul>$1</ul>');

  // Links
  html = html.replace(/\[(.*?)\]\((.*?)\)/gim, '<a href="$2">$1</a>');

  // Line breaks
  html = html.replace(/\n\n/gim, '</p><p>');
  html = '<p>' + html + '</p>';

  // Clean up
  html = html.replace(/<p><h/gim, '<h');
  html = html.replace(/<\/h(\d)><\/p>/gim, '</h$1>');
  html = html.replace(/<p><ul>/gim, '<ul>');
  html = html.replace(/<\/ul><\/p>/gim, '</ul>');
  html = html.replace(/<p><pre>/gim, '<pre>');
  html = html.replace(/<\/pre><\/p>/gim, '</pre>');
  html = html.replace(/<p><\/p>/gim, '');

  return html;
}

export default HtmlExport;
